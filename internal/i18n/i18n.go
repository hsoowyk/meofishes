// Package i18n translates the interface. The English text is the key:
//
//	i18n.T("Queued: {track}", "track", t.String())
//
// Translations are JSON files (English → translated) in assets/locales,
// embedded in the binary, plus any <code>.json in the user's locales folder
// (~/.local/share/meofishes/locales), which override or add languages.
package i18n

import (
	"encoding/json"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"sync"
)

// Language is one available language.
type Language struct {
	Code    string // BCP 47: en, pt-BR, zh-CN…
	Name    string // native name
	RTL     bool
	Strings map[string]string
}

var (
	mu      sync.RWMutex
	langs   = map[string]*Language{"en": {Code: "en", Name: "English"}}
	current = langs["en"]
	missing = map[string]bool{}
	keys    []string
)

// Keys lists every translatable string of the app (locales/keys.json,
// generated by tools/i18nkeys).
func Keys() []string {
	mu.RLock()
	defer mu.RUnlock()
	return keys
}

type file struct {
	Code    string            `json:"code"`
	Name    string            `json:"name"`
	RTL     bool              `json:"rtl,omitempty"`
	Strings map[string]string `json:"strings"`
}

// Load reads every *.json of the embedded folder and of userDir.
func Load(embedded fs.FS, dir string, userDir string) {
	mu.Lock()
	defer mu.Unlock()
	add := func(data []byte) {
		var f file
		if json.Unmarshal(data, &f) != nil || f.Code == "" {
			return
		}
		l := langs[f.Code]
		if l == nil {
			l = &Language{Code: f.Code, Strings: map[string]string{}}
			langs[f.Code] = l
		}
		if f.Name != "" {
			l.Name = f.Name
		}
		l.RTL = l.RTL || f.RTL
		if l.Strings == nil {
			l.Strings = map[string]string{}
		}
		for k, v := range f.Strings {
			if strings.TrimSpace(v) != "" {
				l.Strings[k] = v
			}
		}
	}
	if embedded != nil {
		if data, err := fs.ReadFile(embedded, dir+"/keys.json"); err == nil {
			_ = json.Unmarshal(data, &keys)
		}
		ents, _ := fs.ReadDir(embedded, dir)
		for _, e := range ents {
			if strings.HasSuffix(e.Name(), ".json") {
				if data, err := fs.ReadFile(embedded, dir+"/"+e.Name()); err == nil {
					add(data)
				}
			}
		}
	}
	if userDir != "" {
		ents, _ := os.ReadDir(userDir)
		for _, e := range ents {
			if strings.HasSuffix(e.Name(), ".json") {
				if data, err := os.ReadFile(filepath.Join(userDir, e.Name())); err == nil {
					add(data)
				}
			}
		}
	}
}

// Languages lists the available languages, English first.
func Languages() []*Language {
	mu.RLock()
	defer mu.RUnlock()
	out := make([]*Language, 0, len(langs))
	for _, l := range langs {
		out = append(out, l)
	}
	sort.Slice(out, func(i, j int) bool {
		if out[i].Code == "en" || out[j].Code == "en" {
			return out[i].Code == "en"
		}
		return out[i].Name < out[j].Name
	})
	return out
}

// Set selects the language (unknown codes fall back to English; "pt" finds "pt-BR").
func Set(code string) *Language {
	mu.Lock()
	defer mu.Unlock()
	l := langs[code]
	if l == nil {
		base, _, _ := strings.Cut(code, "-")
		for c, x := range langs {
			if strings.HasPrefix(c, base) {
				l = x
				break
			}
		}
	}
	if l == nil {
		l = langs["en"]
	}
	current = l
	return l
}

// Current is the selected language.
func Current() *Language {
	mu.RLock()
	defer mu.RUnlock()
	return current
}

// T translates s and replaces {name} placeholders with the given pairs.
func T(s string, kv ...string) string {
	mu.RLock()
	out, ok := current.Strings[s]
	if !ok && current.Code != "en" {
		mu.RUnlock()
		mu.Lock()
		missing[s] = true
		mu.Unlock()
		mu.RLock()
	}
	mu.RUnlock()
	if !ok {
		out = s
	}
	for i := 0; i+1 < len(kv); i += 2 {
		out = strings.ReplaceAll(out, "{"+kv[i]+"}", kv[i+1])
	}
	return out
}

// Missing lists the strings used so far with no translation (developer mode).
func Missing() []string {
	mu.RLock()
	defer mu.RUnlock()
	out := make([]string, 0, len(missing))
	for k := range missing {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// Coverage is the fraction of keys translated, given the full key list.
func Coverage(l *Language, keys []string) float64 {
	if l.Code == "en" || len(keys) == 0 {
		return 1
	}
	n := 0
	for _, k := range keys {
		if _, ok := l.Strings[k]; ok {
			n++
		}
	}
	return float64(n) / float64(len(keys))
}
